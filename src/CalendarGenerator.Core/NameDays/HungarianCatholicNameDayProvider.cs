    private static readonly IReadOnlyDictionary<(int Month, int Day), string[]> FixedNames = BuildFixed();

    public string SourceId => "hu-catholic";
    public string DisplayName => "Magyar katolikus névnapok";

    public IReadOnlyList<string> GetNameDays(DateOnly date, string language)
    {
        var names = new List<string>();
        if (FixedNames.TryGetValue((date.Month, date.Day), out var fixedNames))
            names.AddRange(fixedNames);

        var movable = MovableFeastCalculator.GetMovableFeasts(date.Year, language);
        if (movable.TryGetValue(date, out var feast) && !names.Contains(feast, StringComparer.OrdinalIgnoreCase))
            names.Insert(0, feast);

        return names;
    }

